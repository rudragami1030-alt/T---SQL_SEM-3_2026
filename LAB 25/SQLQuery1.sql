-- 5. Implement scalar function to print numbers from 1 to N.
CREATE OR ALTER FUNCTION FN_PRINT_NUMBERS_UPTO_N
(@N INT)
RETURNS INT
AS
BEGIN
    DECLARE @RESULT AS INT = 0;
    DECLARE @I AS INT = 1;
    WHILE @I <= @N
        BEGIN
            SET @RESULT = @RESULT + @I;
            SET @I = @I + 1;
        END
    RETURN @RESULT;
END

SELECT DBO.FN_PRINT_NUMBERS_UPTO_N(10) AS NUMBERS_UPTO_N;

