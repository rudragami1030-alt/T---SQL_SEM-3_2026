--2. Implement scalar function to calculate simple interest. 

CREATE OR ALTER FUNCTION CAL_INT
(
    @P INT,
    @R INT,
    @T INT
)
RETURNS INT
AS
BEGIN
   
    RETURN (@P * @R * @T) / 100.00;
    
END;
SELECT DBO.CAL_INT(7,9,8);

