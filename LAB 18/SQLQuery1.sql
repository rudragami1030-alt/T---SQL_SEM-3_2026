--23. DISPLAY THE STUDENTS WHOSE SPI IS GREATER THAN AT LEAST ONE STUDENT OF EVERY BRANCH.
SELECT S.SNAME, R.SPI
FROM STUDENTINFO S
JOIN RESULT R ON S.RNO = R.RNO
WHERE R.SPI > ALL (SELECT MIN(R1.SPI)
                   FROM STUDENTINFO S1
                   JOIN RESULT R1 ON S1.RNO = R1.RNO
                   GROUP BY S1.BRANCH);

--24. DISPLAY THE STUDENTS WHOSE SPI IS LESS THAN ALL STUDENTS OF CE BRANCH.
SELECT S.SNAME, R.SPI
FROM STUDENTINFO S
JOIN RESULT R ON S.RNO = R.RNO
WHERE R.SPI < ALL (SELECT R1.SPI
                   FROM STUDENTINFO S1
                   JOIN RESULT R1 ON S1.RNO = R1.RNO
                   WHERE S1.BRANCH = 'CE');

--25. DISPLAY THE BRANCH THAT CONTAINS THE STUDENT WITH HIGHEST SPI.
SELECT S.BRANCH
FROM STUDENTINFO S
JOIN RESULT R ON S.RNO = R.RNO
WHERE R.SPI = (SELECT MAX(SPI) FROM RESULT);

--26. DISPLAY THE STUDENTS WHOSE SPI IS LESS THAN THE SPI OF EVERY STUDENT IN CE BRANCH AND GREATER THAN EVERY STUDENT IN ME BRANCH.
SELECT S.SNAME, R.SPI
FROM STUDENTINFO S
JOIN RESULT R ON S.RNO = R.RNO
WHERE R.SPI < ALL (SELECT R1.SPI
                   FROM STUDENTINFO S1
                   JOIN RESULT R1 ON S1.RNO = R1.RNO
                   WHERE S1.BRANCH = 'CE')
  AND R.SPI > ALL (SELECT R2.SPI
                   FROM STUDENTINFO S2
                   JOIN RESULT R2 ON S2.RNO = R2.RNO
                   WHERE S2.BRANCH = 'ME');
