--15. DISPLAY THE STUDENTS WHOSE SPI IS LESS THAN ANY STUDENT OF ME BRANCH.
SELECT * FROM STUDENTINFO S
JOIN RESULT R ON S.RNO = R.RNO
WHERE SPI < ANY (SELECT SPI
                 FROM STUDENTINFO S
                 JOIN RESULT R ON S.RNO = R.RNO
                 WHERE S.BRANCH = 'ME');

--16. DISPLAY THE STUDENT DETAILS WHOSE SPI IS NOT EQUAL TO ANY SPI OF EC BRANCH STUDENTS.
SELECT * FROM STUDENTINFO S
JOIN RESULT R ON S.RNO = R.RNO
WHERE SPI NOT IN (SELECT SPI
                  FROM STUDENTINFO S
                  JOIN RESULT R ON S.RNO = R.RNO
                  WHERE S.BRANCH = 'EC');

--17. DISPLAY THE NAMES OF STUDENTS WHO SCORED HIGHER SPI THAN STUDENT OF RNO 103.
SELECT S.SNAME
FROM STUDENTINFO S
JOIN RESULT R ON S.RNO = R.RNO
WHERE R.SPI > (SELECT SPI FROM RESULT WHERE RNO = 103);

--18. DISPLAY THE STUDENTS WHOSE SPI IS GREATER THAN AVERAGE SPI OF THEIR OWN BRANCH.
SELECT S.SNAME, S.BRANCH, R.SPI
FROM STUDENTINFO S
JOIN RESULT R ON S.RNO = R.RNO
WHERE R.SPI > (SELECT AVG(R1.SPI)
               FROM STUDENTINFO S1
               JOIN RESULT R1 ON S1.RNO = R1.RNO
               WHERE S1.BRANCH = S.BRANCH);

--19. DISPLAY THE STUDENTS WHOSE SPI IS GREATER THAN THE AVERAGE SPI OF CE BRANCH BUT GREATER THAN THE MAXIMUM SPI OF ME BRANCH.
SELECT S.SNAME, R.SPI
FROM STUDENTINFO S
JOIN RESULT R ON S.RNO = R.RNO
WHERE R.SPI > (SELECT AVG(R1.SPI)
               FROM STUDENTINFO S1
               JOIN RESULT R1 ON S1.RNO = R1.RNO
               WHERE S1.BRANCH = 'CE')
  AND R.SPI > (SELECT MAX(R2.SPI)
               FROM STUDENTINFO S2
               JOIN RESULT R2 ON S2.RNO = R2.RNO
               WHERE S2.BRANCH = 'ME');

--20. DISPLAY THE BRANCH NAMES WHOSE AVERAGE SPI IS GREATER THAN THE OVERALL AVERAGE SPI.
SELECT S.BRANCH, AVG(R.SPI) AS AVG_SPI
FROM STUDENTINFO S
JOIN RESULT R ON S.RNO = R.RNO
GROUP BY S.BRANCH
HAVING AVG(R.SPI) > (SELECT AVG(SPI) FROM RESULT);

--21. DISPLAY THE STUDENTS WHO HAVE MAXIMUM SPI IN THEIR RESPECTIVE BRANCH.
SELECT S.SNAME, S.BRANCH, R.SPI
FROM STUDENTINFO S
JOIN RESULT R ON S.RNO = R.RNO
WHERE R.SPI = (SELECT MAX(R1.SPI)
               FROM STUDENTINFO S1
               JOIN RESULT R1 ON S1.RNO = R1.RNO
               WHERE S1.BRANCH = S.BRANCH);

--22. DISPLAY THE STUDENTS WHOSE SPI IS GREATER THAN THEIR AVERAGE SPI OF THEIR BRANCH AND GREATER THAN OVERALL AVERAGE SPI.
SELECT S.SNAME, S.BRANCH, R.SPI
FROM STUDENTINFO S
JOIN RESULT R ON S.RNO = R.RNO
WHERE R.SPI > (SELECT AVG(R1.SPI)
               FROM STUDENTINFO S1
               JOIN RESULT R1 ON S1.RNO = R1.RNO
               WHERE S1.BRANCH = S.BRANCH)
  AND R.SPI > (SELECT AVG(SPI) FROM RESULT);


