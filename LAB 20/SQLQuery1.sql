--16. DISPLAY STUDENTS WHOSE SPI IS GREATER THAN THE PREVIOUS STUDENT AND LESS THAN THE NEXT STUDENT.
SELECT SNAME, PERFORMANCE,
       LAG(PERFORMANCE) OVER(ORDER BY PERFORMANCE) AS PREVIOUS_SPI,
       LEAD(PERFORMANCE) OVER(ORDER BY PERFORMANCE) AS NEXT_SPI
FROM STUDENT
WHERE PERFORMANCE > LAG(PERFORMANCE) OVER(ORDER BY PERFORMANCE)
  AND PERFORMANCE < LEAD(PERFORMANCE) OVER(ORDER BY PERFORMANCE);

--17. DISPLAY BRANCH-WISE SECOND TOPPER STUDENTS.
SELECT STDID, SNAME, BRANCH, PERFORMANCE
FROM (
    SELECT STDID, SNAME, BRANCH, PERFORMANCE,
           ROW_NUMBER() OVER(PARTITION BY BRANCH ORDER BY PERFORMANCE DESC) AS RN
    FROM STUDENT
) AS SUB
WHERE RN = 2;

--20. DISPLAY STUDENTS WHOSE SPI DIFFERENCE WITH PREVIOUS STUDENT IS MAXIMUM.
