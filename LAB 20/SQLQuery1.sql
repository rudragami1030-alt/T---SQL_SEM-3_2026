--From the table STUDENT perform the following queries:

--Part – A:

SELECT * FROM STUDENT

--1. Display rank of students based on SPI.

SELECT STDID ,SNAME , CITY ,PERFORMANCE ,BRANCH , ROW_NUMBER() OVER(
ORDER BY PERFORMANCE DESC
) AS RN
FROM STUDENT


--2. Display dense rank of students based on SPI.

SELECT STDID ,SNAME , CITY ,PERFORMANCE ,BRANCH , DENSE_RANK() OVER
(ORDER BY SPI DESC) AS D_RANK
FROM STUDENT


--3. Display sequential number for each student record.

SELECT STDID ,SNAME , CITY ,PERFORMANCE ,BRANCH , ROW_NUMBER() OVER(
ORDER BY SPI DESC
) AS RN
FROM STUDENT 


--4. Display branch-wise rank of students.

SELECT STDID ,SNAME , CITY ,PERFORMANCE ,BRANCH , RANK() OVER
(PARTITION BY BRANCH
ORDER BY SPI DESC)
AS R
FROM STUDENT


--5. Display branch-wise dense ranking of students.

SELECT STDID ,SNAME , CITY ,PERFORMANCE ,BRANCH , DENSE_RANK() OVER
(PARTITION BY BRANCH
ORDER BY PERFORMANCE DESC) AS D_RANK
FROM STUDENT


--6. Display branch-wise sequential numbering of students.

SELECT STDID ,SNAME , CITY ,PERFORMANCE ,BRANCH , ROW_NUMBER() OVER(
PARTITION BY BRANCH
ORDER BY PERFORMANCE DESC
) AS RN
FROM STUDENT


--7. Display SNAME, Current SPI, Previous SPI and SPI Difference with previous student in ascending order of SPI.

SELECT SNAME , PERFORMANCE , LAG(PERFORMANCE) OVER(ORDER BY PERFORMANCE) AS PREVIOUS_SPI , (PERFORMANCE - (LAG(PERFORMANCE) OVER (ORDER BY PERFORMANCE))) AS DIFF
FROM STUDENT


--8. Display SNAME, Current SPI, Next SPI and SPI Difference with next student in descending order of SPI.

SELECT SNAME ,PERFORMANCE , LEAD(PERFORMANCE) OVER
(ORDER BY PERFORMANCE DESC) AS NEXT_SPI , (PERFORMANCE - (LEAD(PERFORMANCE) OVER (ORDER BY PERFORMANCE DESC))) AS DIFF
FROM STUDENT

--9. Display top 3 students based on SPI.

SELECT TOP 3 STDID ,SNAME , CITY , PERFORMANCE ,BRANCH , ROW_NUMBER() OVER(
ORDER BY SPI DESC
) AS RN
FROM STUDENT


--10. Display top 2 students from each branch.

SELECT TOP 2 STDID ,SNAME , CITY , PERFORMANCE ,BRANCH , ROW_NUMBER() OVER(
PARTITION BY BRANCH
ORDER BY PERFORMANCE DESC
) AS RN
FROM STUDENT

